/**
 * Runs every automated test suite and records the real results for the Testing & UAT screen
 * (SOW 14.6 Stage 1 evidence). Writes src/data/mock/generated/testRunResults.ts.
 *   npm run report:tests
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const SUITES = [
  { script: "test:schemes", module: "Schemes & incentives", area: "Scheme Builder, settlement, tiers, referrals, campaigns" },
  { script: "test:wallet", module: "Wallet, TDS & redemption", area: "Ledger, adjustments, TDS, redemption, payouts" },
  { script: "test:comms", module: "Communication Centre", area: "Notifications, templates, bot, helpdesk" },
  { script: "test:gifts", module: "Gifts, vouchers & insurance", area: "Catalogue, vouchers, fulfilment, insurance" },
  { script: "test:risk", module: "Fraud & risk", area: "Fraud queue, devices, QR, data integrity" },
  { script: "test:ops", module: "Integration monitoring", area: "Integrations, retry, health, incidents" },
  { script: "test:analytics", module: "Analytics & reporting", area: "KPIs, dashboards, finance reports, exports" },
  { script: "test:platform", module: "Platform administration", area: "View-As, RBAC governance, readiness" },
  { script: "test:jobs", module: "Proposed Module 12 (prototype)", area: "Job management & field tooling — demo mode" },
  { script: "test:demo", module: "Client demo simulation", area: "Cross-module acceptance, resets, environment safety" },
  { script: "test:schemes:gaps", module: "Scheme audit probes", area: "Known-gap probes (Phase 6 audit)" },
];
const runs = SUITES.map((s) => {
  const started = Date.now();
  let out = "";
  let exit = 0;
  try {
    out = execSync(`npm run -s ${s.script}`, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 64 * 1024 * 1024 });
  } catch (e) {
    out = `${e.stdout ?? ""}${e.stderr ?? ""}`;
    exit = e.status ?? 1;
  }
  const m = out.match(/(\d+)\/(\d+) passed/);
  const g = out.match(/(\d+) of (\d+) probes confirmed a gap/);
  const failed = [...out.matchAll(/^FAIL\s+(\d+)\s+\[[a-z]+\] (.+?)(?: — .*)?$/gm)].map((x) => `${x[1]} ${x[2]}`).slice(0, 20);
  return { ...s, passed: m ? Number(m[1]) : g ? Number(g[2]) - Number(g[1]) : 0, total: m ? Number(m[2]) : g ? Number(g[2]) : 0, gapsConfirmed: g ? Number(g[1]) : null, exit, failed, ms: Date.now() - started, found: Boolean(m || g) };
});
const at = new Date().toISOString().slice(0, 16);
const body = `/* Generated by scripts/collect-test-results.mjs (npm run report:tests) on ${at}. Do not edit. */\nexport const TEST_RUN = ${JSON.stringify({ at, environment: "Local development machine (Node, in-browser stores)", buildRef: "Working copy (uncommitted)", runs }, null, 2)} as const;\n`;
writeFileSync("src/data/mock/generated/testRunResults.ts", body);
for (const r of runs) console.log(`${r.script.padEnd(20)} ${r.found ? `${r.passed}/${r.total}` : "not run"}${r.gapsConfirmed != null ? ` (${r.gapsConfirmed} gaps confirmed)` : ""} exit=${r.exit}`);
