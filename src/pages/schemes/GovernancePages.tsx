import { useEffect, useState } from "react";
import { useSearchParams } from "react-router-dom";
import { Download } from "lucide-react";
import { Panel } from "@/components/ui/Panel";
import { DataTable, type Column } from "@/components/ui/DataTable";
import { Drawer } from "@/components/ui/Overlay";
import { SelectInput, Tabs, TextArea, TextField } from "@/components/form/Form";
import { useToast } from "@/context/ToastContext";
import { BUILDER_COMPONENTS, DECISION_STATUS, GUIDE_SECTIONS, SERVICE_CONTRACTS } from "@/config/schemeCatalogue";
import { confirmFormula, updateSchemeDecision } from "@/features/schemes/store";
import type { DecisionStatus, Formula, SchemeDecision } from "@/types/schemes";
import { PolicyMessages, SectionTitle } from "@/pages/users/shared";
import { Notice } from "@/pages/approvals/shared";
import { SchemeAuditTable } from "./SchemeDetailPage";
import { DecisionBadge, DecisionRef, useSchemeView } from "./shared";

type Res = { ok: boolean; errors: string[]; warnings: string[] } | null;

export function SchemeGovernancePage() {
  const v = useSchemeView();
  const [params, setParams] = useSearchParams();
  const tab = params.get("tab") ?? "decisions";
  const [edit, setEdit] = useState<SchemeDecision | null>(null);
  const [formula, setFormula] = useState<Formula | null>(null);
  const [result, setResult] = useState<Res>(null);
  const admin = v.can("users:manage");
  useEffect(() => {
    const id = window.location.hash.slice(1);
    if (id) document.getElementById(`dec-${id}`)?.scrollIntoView({ block: "center" });
  }, [tab]);
  const guideMd = () => [`# Scheme Configuration Guide (template)`, ``, `Ownership: pending confirmation (OP-SB-GUIDE). Development template generated by the portal.`, ``, ...GUIDE_SECTIONS.flatMap((g) => [`## ${g.title}`, ...g.steps.map((s, i) => `${i + 1}. ${s}`), ``])].join("\n");
  return (
    <>
      <SectionTitle title="Scheme governance" description="Open business decisions, formula registry, audit trail, configuration guide and integration contracts" />
      <PolicyMessages result={result} />
      <Tabs label="Governance sections" value={tab} onChange={(t) => setParams({ tab: t })} tabs={[{ id: "decisions", label: "Decision register", count: v.s.decisions.filter((d) => d.status !== "confirmed").length }, { id: "formulas", label: "Formula registry" }, { id: "audit", label: "Audit trail" }, { id: "guide", label: "Configuration guide" }, { id: "coverage", label: "SOW coverage" }, { id: "contracts", label: "Integration contracts" }]} />
      {tab === "decisions" && (
        <>
          <Notice tone="warn">An open point is never removed because the screen exists. Confirming a decision changes no configuration by itself: formulas are recorded separately, then schemes are revalidated and resubmitted.</Notice>
          <Panel level={3} padded={false}>
            <DataTable rows={v.s.decisions} rowKey={(d) => d.id} caption="Scheme decision register" pageSize={25} onRowClick={admin ? (d) => setEdit(structuredClone(d)) : undefined} rowActionLabel={(d) => `Update ${d.id}`} columns={[
              { key: "id", header: "Reference", value: (d) => d.id, render: (d) => <span id={`dec-${d.id}`} className="mono small">{d.id}</span> },
              { key: "src", header: "Source", value: (d) => d.source, render: (d) => <span className="small">{d.source === "sow" ? "SOW 6.7" : "Raised in build"}</span> },
              { key: "d", header: "Open business decision", value: (d) => d.description, render: (d) => <span className="cell-wrap">{d.description}</span> },
              { key: "o", header: "Business owner", value: (d) => d.owner },
              { key: "st", header: "Status", value: (d) => d.status, render: (d) => <DecisionBadge status={d.status} /> },
              { key: "i", header: "Impacted configuration", value: (d) => d.impacted, render: (d) => <span className="small cell-wrap">{d.impacted}</span> },
              { key: "r", header: "Activation restriction", value: (d) => d.restriction, render: (d) => <span className="small cell-wrap">{d.restriction}</span> },
              { key: "n", header: "Confirmation notes", value: (d) => d.notes, render: (d) => <span className="small cell-wrap">{d.notes || "—"}</span> },
            ] as Column<SchemeDecision>[]} />
          </Panel>
        </>
      )}
      {tab === "formulas" && (
        <Panel level={3} title="Formula registry" subtitle="Calculations that are not an explicit Maker-entered value. Each needs its decision confirmed before a version can be recorded" padded={false}>
          <DataTable rows={v.s.formulas} rowKey={(f) => f.id} caption="Formula registry" searchable={false} onRowClick={v.can("schemes:configure_formula") ? (f) => setFormula(f) : undefined} columns={[
            { key: "id", header: "Formula", value: (f) => f.id, render: (f) => <span className="mono small">{f.id}</span> },
            { key: "n", header: "Name", value: (f) => f.name },
            { key: "a", header: "Applies to", value: (f) => f.appliesTo },
            { key: "d", header: "Decision", value: (f) => f.decisionRef, render: (f) => <DecisionRef id={f.decisionRef} /> },
            { key: "st", header: "Status", value: (f) => f.status, render: (f) => <span className={f.status === "confirmed" ? "" : "warn-text"}>{f.status === "confirmed" ? `Confirmed v${f.version}` : "Pending business formula"}</span> },
            { key: "def", header: "Definition", value: (f) => f.definition, render: (f) => <span className="small cell-wrap">{f.definition || "—"}</span> },
          ] as Column<Formula>[]} />
        </Panel>
      )}
      {tab === "audit" && <SchemeAuditTable rows={v.s.audit} v={v} name="scheme-audit" />}
      {tab === "guide" && (
        <Panel level={3} title="Scheme Configuration Guide · template" subtitle="SOW 6.2.21 is a documentation deliverable. Ownership is pending (OP-SB-GUIDE)" actions={<button type="button" className="btn btn--secondary btn--sm" onClick={() => { const url = URL.createObjectURL(new Blob([guideMd()], { type: "text/markdown" })); const a = document.createElement("a"); a.href = url; a.download = "scheme-configuration-guide-template.md"; a.click(); setTimeout(() => URL.revokeObjectURL(url), 1000); }}><Download size={14} aria-hidden="true" />Download template</button>}>
          <Notice tone="info">Neither Evolve nor V-Guard is assumed to own the final guide. Owner: <strong>{v.s.decisions.find((d) => d.id === "OP-SB-GUIDE")?.owner}</strong> · <DecisionRef id="OP-SB-GUIDE" /></Notice>
          <div className="guide">{GUIDE_SECTIONS.map((g) => <section key={g.id}><h3>{g.title}</h3><ol>{g.steps.map((s) => <li key={s}>{s}</li>)}</ol></section>)}</div>
        </Panel>
      )}
      {tab === "coverage" && (
        <Panel level={3} title="Scheme Builder components (SOW 6.2.1–6.2.21)" padded={false}>
          <DataTable rows={BUILDER_COMPONENTS} rowKey={(b) => String(b.n)} caption="Component coverage" searchable={false} pageSize={25} columns={[
            { key: "n", header: "#", value: (b) => b.n },
            { key: "s", header: "SOW", value: (b) => b.sow },
            { key: "name", header: "Component", value: (b) => b.name },
            { key: "w", header: "Where in the portal", value: (b) => b.where },
            { key: "d", header: "Open decision", value: (b) => b.decision ?? "", render: (b) => (b.decision ? <DecisionRef id={b.decision} /> : <span className="muted small">—</span>) },
          ] as Column<(typeof BUILDER_COMPONENTS)[number]>[]} />
        </Panel>
      )}
      {tab === "contracts" && (
        <Panel level={3} title="Backend service contracts" subtitle="Prepared for the backend team. None is connected; paths are proposals, not live endpoints" padded={false}>
          <DataTable rows={SERVICE_CONTRACTS} rowKey={(c) => c.operation} caption="Service contracts" searchable={false} pageSize={20} columns={[
            { key: "s", header: "Service", value: (c) => c.service },
            { key: "o", header: "Operation", value: (c) => c.operation },
            { key: "m", header: "Method · path", value: (c) => `${c.method} ${c.path}`, render: (c) => <span className="mono small">{c.method} {c.path}</span> },
            { key: "i", header: "Idempotency", value: (c) => c.idempotency, render: (c) => <span className="small">{c.idempotency}</span> },
            { key: "st", header: "Status", value: (c) => c.status, render: (c) => <span className="small warn-text">{c.status}</span> },
          ] as Column<(typeof SERVICE_CONTRACTS)[number]>[]} />
        </Panel>
      )}
      {edit && <DecisionDrawer d={edit} onClose={() => setEdit(null)} setResult={setResult} uid={v.uid} />}
      {formula && <FormulaDrawer f={formula} onClose={() => setFormula(null)} setResult={setResult} uid={v.uid} />}
    </>
  );
}

function DecisionDrawer({ d, onClose, setResult, uid }: { d: SchemeDecision; onClose: () => void; setResult: (r: Res) => void; uid: string }) {
  const { notify } = useToast();
  const [x, setX] = useState(d);
  return (
    <Drawer open onClose={onClose} title={`${d.id}`} subtitle={d.description} footer={<button type="button" className="btn btn--primary" onClick={() => { const r = updateSchemeDecision(uid, d.id, { status: x.status, notes: x.notes, owner: x.owner }); setResult(r); if (r.ok) { notify("Decision updated", "positive"); onClose(); } }}>Save</button>}>
      <SelectInput label="Status" value={x.status} onChange={(s) => setX({ ...x, status: s as DecisionStatus })} options={(Object.keys(DECISION_STATUS) as DecisionStatus[]).map((k) => ({ value: k, label: DECISION_STATUS[k].label }))} />
      <TextField label="Business owner" value={x.owner} onChange={(o) => setX({ ...x, owner: o })} />
      <TextArea label="Confirmation notes (answer and who confirmed)" value={x.notes} onChange={(n) => setX({ ...x, notes: n })} />
    </Drawer>
  );
}

function FormulaDrawer({ f, onClose, setResult, uid }: { f: Formula; onClose: () => void; setResult: (r: Res) => void; uid: string }) {
  const { notify } = useToast();
  const [version, setVersion] = useState(f.version ?? "");
  const [def, setDef] = useState(f.definition);
  return (
    <Drawer open onClose={onClose} title={`${f.id} · ${f.name}`} subtitle={`Requires ${f.decisionRef} to be confirmed`} footer={<button type="button" className="btn btn--primary" onClick={() => { const r = confirmFormula(uid, f.id, version, def); setResult(r); if (r.ok) { notify("Formula recorded", "positive"); onClose(); } }}>Record confirmed formula</button>}>
      <TextField label="Formula version" value={version} onChange={setVersion} />
      <TextArea label="Confirmed definition (as approved by V-Guard)" value={def} onChange={setDef} rows={5} />
      <p className="small muted">The definition is documentation for the backend engine; the portal never executes it.</p>
    </Drawer>
  );
}
